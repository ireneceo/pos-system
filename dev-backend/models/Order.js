const { DataTypes, Model } = require('sequelize');
const database = require('../config/database');

class Order extends Model {}

Order.init({
  id: {
    type: DataTypes.INTEGER,
    primaryKey: true,
    autoIncrement: true
  },
  restaurant_id: {
    type: DataTypes.INTEGER,
    allowNull: false
  },
  customer_id: {
    type: DataTypes.INTEGER,
    allowNull: true,
    comment: 'Customer ID for logged-in users'
  },
  order_number: {
    type: DataTypes.STRING(50),
    allowNull: true  // Generated by backend, can be null temporarily during creation
  },
  customer_name: {
    type: DataTypes.STRING(255),
    allowNull: true
  },
  customer_phone: {
    type: DataTypes.STRING(50),
    allowNull: true
  },
  table_number: {
    type: DataTypes.STRING(10),
    allowNull: true
  },
  floor_plan_table_id: {
    type: DataTypes.STRING(64),
    allowNull: true,
    comment: 'Floor plan v2 tables[].id (e.g. "t_abc123"). Disambiguates same table_number across different zones. NULL for legacy orders (pre-2026-05-27).'
  },
  guest_count: {
    type: DataTypes.INTEGER,
    allowNull: true,
    defaultValue: null,
    comment: 'Number of guests at the table (dine-in only)'
  },
  pager_number: {
    type: DataTypes.STRING(10),
    allowNull: true,
    comment: 'Pager device number for order notification'
  },
  total_amount: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: false
  },
  status: {
    type: DataTypes.ENUM('awaiting_payment', 'pending', 'preparing', 'ready', 'served', 'completed', 'cancelled', 'outstanding'),
    defaultValue: 'awaiting_payment'
  },
  // 2026-05-28 매장 critical: source 무관 (POS/모바일/FloorPlan) 주문 발생 직후
  // backend 가 set, 매장 device 가 polling 으로 catch → 인쇄 후 false set.
  // Frontend socket 의존성을 제거. backend 가 단일 진실.
  needs_print: {
    type: DataTypes.BOOLEAN,
    defaultValue: false,
    comment: 'Pending kitchen auto-print flag. Set true on Order.create. Cleared by frontend.'
  },
  // 2026-05-28: needs_bill — separate flag for cashier bill receipt auto-print.
  // Set true on merge (mobile 같은 테이블 추가 = staff 주문관리용 누적 영수증).
  // Single new orders 는 false (결제 버튼 시점에만 bill 인쇄).
  needs_bill: {
    type: DataTypes.BOOLEAN,
    defaultValue: false,
    comment: 'Pending bill auto-print flag. Set true on merge (mobile 같은 테이블 추가).'
  },
  order_type: {
    type: DataTypes.ENUM('dine_in', 'takeaway', 'delivery', 'pickup', 'reservation_deposit'),
    defaultValue: 'dine_in'
  },
  reservation_id: {
    type: DataTypes.INTEGER,
    allowNull: true,
    references: { model: 'reservations', key: 'id' },
    comment: 'FK to Reservation when this order is a deposit prepayment or a reservation-attached order'
  },
  source: {
    type: DataTypes.ENUM('pos', 'mobile', 'kiosk'),
    defaultValue: 'pos',
    comment: 'Order source: pos (POS Terminal), mobile (Mobile Order), kiosk (Self-service Kiosk)'
  },
  payment_method: {
    type: DataTypes.STRING(50),
    allowNull: true
  },
  card_type: {
    type: DataTypes.STRING(20),
    allowNull: true,
    comment: 'Card type when payment_method is card: visa, master, amex, other'
  },
  payment_status: {
    type: DataTypes.ENUM('pending', 'partial', 'completed', 'failed', 'payment_verification_pending', 'rejected'),
    defaultValue: 'pending'
  },
  // Split bill 누적 결제액. amount_paid >= total_amount 이면 payment_status='completed'.
  amount_paid: {
    type: DataTypes.DECIMAL(10, 2),
    defaultValue: 0,
    allowNull: false
  },
  payment_intent_id: {
    type: DataTypes.STRING(255),
    allowNull: true,
    comment: 'Stripe PaymentIntent ID or PayPal Order ID for online payments'
  },
  payment_provider: {
    type: DataTypes.STRING(20),
    allowNull: true,
    comment: 'Payment provider: stripe, paypal'
  },
  transaction_id: {
    type: DataTypes.STRING(255),
    allowNull: true,
    comment: 'Payment transaction ID from provider'
  },
  kitchen_ready: {
    type: DataTypes.BOOLEAN,
    defaultValue: false,
    comment: 'True when payment is completed OR Proceed Without Payment is clicked'
  },
  order_date: {
    type: DataTypes.DATE,
    defaultValue: DataTypes.NOW
  },
  order_items: {
    type: DataTypes.TEXT,
    allowNull: true,
    get() {
      const value = this.getDataValue('order_items');
      return value ? JSON.parse(value) : null;
    },
    set(value) {
      this.setDataValue('order_items', value ? JSON.stringify(value) : null);
    }
  },
  payment_proof: {
    type: DataTypes.TEXT('long'),
    allowNull: true,
    get() {
      const value = this.getDataValue('payment_proof');
      return value ? JSON.parse(value) : null;
    },
    set(value) {
      this.setDataValue('payment_proof', value ? JSON.stringify(value) : null);
    }
  },
  subtotal: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: true,
    comment: 'Subtotal before tax and service charge'
  },
  tax: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: true,
    defaultValue: 0,
    comment: 'Tax amount'
  },
  tax_rate: {
    type: DataTypes.DECIMAL(5, 2),
    allowNull: true,
    defaultValue: 6,
    comment: 'Tax rate percentage'
  },
  service_charge: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: true,
    defaultValue: 0,
    comment: 'Service charge amount'
  },
  service_charge_rate: {
    type: DataTypes.DECIMAL(5, 2),
    allowNull: true,
    defaultValue: 10,
    comment: 'Service charge rate percentage'
  },
  discount: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: true,
    defaultValue: 0,
    comment: 'Fixed discount amount'
  },
  discount_policy_name: {
    type: DataTypes.STRING(50),
    allowNull: true,
    comment: 'Discount policy name (e.g., "20%", "Staff", "VIP")'
  },
  discount_policy_amount: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: true,
    defaultValue: 0,
    comment: 'Percentage-based discount policy amount'
  },
  coupon_code: {
    type: DataTypes.STRING(50),
    allowNull: true,
    comment: 'Coupon code applied'
  },
  coupon_discount: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: true,
    defaultValue: 0,
    comment: 'Coupon discount amount'
  },
  takeaway_charge: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: true,
    defaultValue: 0,
    comment: 'Takeaway charge amount'
  },
  served_at: {
    type: DataTypes.DATE,
    allowNull: true,
    comment: 'Timestamp when order status changed to served'
  },
  scheduled_pickup_time: {
    type: DataTypes.DATE,
    allowNull: true,
    comment: 'Scheduled pickup time for pre-order pickup'
  },
  delivery_info: {
    type: DataTypes.TEXT,
    allowNull: true,
    comment: 'Delivery information (address, phone, notes, zone)',
    get() {
      const value = this.getDataValue('delivery_info');
      return value ? JSON.parse(value) : null;
    },
    set(value) {
      this.setDataValue('delivery_info', value ? JSON.stringify(value) : null);
    }
  },
  delivery_fee: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: true,
    defaultValue: 0,
    comment: 'Delivery fee amount'
  },
  points_used: {
    type: DataTypes.INTEGER,
    allowNull: true,
    defaultValue: 0,
    comment: 'Points used for this order'
  },
  point_discount: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: true,
    defaultValue: 0,
    comment: 'Discount amount from points usage'
  },
  cashier_id: {
    type: DataTypes.INTEGER,
    allowNull: true,
    comment: 'Staff who processed this order (POS cashier)'
  },
  cashier_name: {
    type: DataTypes.STRING(255),
    allowNull: true,
    comment: 'Cashier name snapshot (preserved after staff changes)'
  },
  is_deleted: {
    type: DataTypes.BOOLEAN,
    allowNull: false,
    defaultValue: false,
    comment: 'Soft delete flag - order number is preserved'
  },
  deleted_at: {
    type: DataTypes.DATE,
    allowNull: true,
    comment: 'Timestamp when order was soft deleted'
  }
}, {
  sequelize: database.sequelize,
  modelName: 'Order',
  tableName: 'orders',
  timestamps: true
});

module.exports = Order;
